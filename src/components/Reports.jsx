// Floating-element content generators. Each floating element stores its own
// config flat on the object (color, bold, bgColor, linkedVar, rows/cols...);
// these functions turn that config into HTML on demand, so changing a color
// or which variable a QR code points to updates instantly.
// ---------------------------------------------------------------------------
function generateTableHTML(rows, cols) {
  let html = '<table style="width:100%;height:100%;border-collapse:collapse;">';
  for (let r = 0; r < rows; r++) {
    html += '<tr>';
    for (let c = 0; c < cols; c++) {
      html += `<td style="border:1px solid #cbd5e1;padding:6px;min-width:24px;">${r === 0 ? `Column ${c + 1}` : '&nbsp;'}</td>`;
    }
    html += '</tr>';
  }
  html += '</table>';
  return html;
}

